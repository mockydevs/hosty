"""Quadlet renderer (v2/M2): exact-text snapshots for every variant, path
layout, the spec-hash marker round-trip, and proof that injection cannot
reach unit text (the spec grammar rejects it at construction)."""

from __future__ import annotations

import pytest

from app.domain.specs import EndpointSpec, ServiceSpec, StackSpec, VolumeSpec, spec_hash
from app.domain.validate import SpecValidationError
from app.system import quadlet
from app.system.tenants import InvalidTenantUserError


def full_stack() -> StackSpec:
    return StackSpec(
        name="blog",
        tenant="hosty-t-7",
        services=(
            ServiceSpec(
                name="web",
                image="docker.io/library/nginx:1.27@sha256:" + "a" * 64,
                env=(("APP_ENV", "prod"), ("WP_HOME", "https://blog.example.com")),
                internal_port=80,
                host_port=20001,
                memory_mb=512,
                cpu_percent=150,
                is_web=True,
            ),
            ServiceSpec(name="db", image="docker.io/library/mariadb:11"),
        ),
        volumes=(
            VolumeSpec(name="content", service="web", mount_path="/var/www/html"),
            VolumeSpec(name="dbdata", service="db", mount_path="/var/lib/mysql"),
        ),
        endpoints=(EndpointSpec(domain="blog.example.com", service="web"),),
    )


def test_container_unit_snapshot_full():
    stack = full_stack()
    web = stack.services[0]
    assert quadlet.container_unit(stack, web) == (
        "# hosty-managed — generated by the panel; manual edits are overwritten\n"
        "# hosty-stack=blog\n"
        "# hosty-service=web\n"
        f"# hosty-spec-hash={spec_hash(stack, web)}\n"
        "\n"
        "[Unit]\n"
        "Description=hosty stack blog — service web\n"
        "\n"
        "[Container]\n"
        "ContainerName=blog-web\n"
        "Image=docker.io/library/nginx:1.27@sha256:" + "a" * 64 + "\n"
        "Network=blog.network\n"
        "NoNewPrivileges=true\n"
        "LogDriver=journald\n"
        "Label=hosty.stack=blog\n"
        "Label=hosty.managed=1\n"
        "PublishPort=127.0.0.1:20001:80\n"
        "EnvironmentFile=/home/hosty-t-7/stacks/blog/env/web.env\n"
        "Volume=/home/hosty-t-7/stacks/blog/volumes/content:/var/www/html\n"
        "PodmanArgs=--memory=512m --cpus=1.5\n"
        "\n"
        "[Service]\n"
        "Restart=always\n"
        "TimeoutStartSec=300\n"
        "\n"
        "[Install]\n"
        "WantedBy=default.target\n"
    )


