def test_network_unit_snapshot():
    assert quadlet.network_unit(full_stack()) == (
        "# hosty-managed — generated by the panel; manual edits are overwritten\n"
        "# hosty-stack=blog\n"
        "\n"
        "[Network]\n"
        "NetworkName=hosty-blog\n"
        "Label=hosty.stack=blog\n"
        "Label=hosty.managed=1\n"
    )


def test_unit_files_is_the_complete_set():
    files = quadlet.unit_files(full_stack())
    assert sorted(files) == ["blog-db.container", "blog-web.container", "blog.network"]


def test_env_files_only_for_services_with_env():
    env_files = quadlet.env_files(full_stack())
    assert list(env_files) == ["/home/hosty-t-7/stacks/blog/env/web.env"]
    assert env_files["/home/hosty-t-7/stacks/blog/env/web.env"] == (
        "APP_ENV=prod\nWP_HOME=https://blog.example.com\n"
    )


def test_spec_hash_marker_round_trips():
    stack = full_stack()
    web = stack.services[0]
    assert quadlet.read_spec_hash(quadlet.container_unit(stack, web)) == spec_hash(stack, web)


def test_ownership_markers_round_trip():
    stack = full_stack()
    text = quadlet.container_unit(stack, stack.services[0])
    assert quadlet.read_stack_marker(text) == "blog"
    assert quadlet.read_service_marker(text) == "web"
    assert quadlet.read_stack_marker(quadlet.network_unit(stack)) == "blog"
    assert quadlet.read_service_marker(quadlet.network_unit(stack)) is None
    assert quadlet.read_stack_marker("garbage") is None
    assert quadlet.read_stack_marker(None) is None


@pytest.mark.parametrize(
    "garbage",
    ["", "[Container]\nImage=x\n", "# hosty-spec-hash=NOT-HEX\n", "# hosty-spec-hash=abc\n", None],
)
def test_read_spec_hash_is_total(garbage):
    assert quadlet.read_spec_hash(garbage) is None


def test_paths():
    assert quadlet.unit_dir(5001) == "/etc/containers/systemd/users/5001"
    assert quadlet.volume_host_dir("hosty-t-7", "blog", "content") == (
        "/home/hosty-t-7/stacks/blog/volumes/content"
    )
    assert quadlet.env_file_path("hosty-t-7", "blog", "web") == (
        "/home/hosty-t-7/stacks/blog/env/web.env"
    )
    assert quadlet.service_unit_name("blog", "web") == "blog-web.service"


@pytest.mark.parametrize("uid", [0, -1, True, "5001", None])
def test_unit_dir_rejects_bad_uids(uid):
    with pytest.raises(ValueError):
        quadlet.unit_dir(uid)


def test_path_helpers_reject_non_tenant_users():
    with pytest.raises(InvalidTenantUserError):
        quadlet.volume_host_dir("root", "blog", "content")


def test_injection_cannot_reach_unit_text():
    """The renderer only accepts validated specs; every injection attempt
    dies at spec construction, so no escaping logic exists to get wrong."""
    with pytest.raises(SpecValidationError):
        ServiceSpec(name="web", image="-rm -rf /")  # leading dash
    with pytest.raises(SpecValidationError):
        ServiceSpec(name="web", image="nginx", env=(("EVIL", "a\n[Service]\nExecStart=sh"),))
    with pytest.raises(SpecValidationError):
        VolumeSpec(name="data", service="web", mount_path="/data:/etc")  # `:` split
    with pytest.raises(SpecValidationError):
        VolumeSpec(name="data", service="web", mount_path="/data/../../etc")
    with pytest.raises(SpecValidationError):
        StackSpec(name="blog\n", tenant="hosty-t-7", services=(ServiceSpec("web", "nginx"),))
